"""Out-of-distribution web-scenario check; not part of model selection.

Run: python -m web.scenario_audit
"""

from __future__ import annotations

import csv

import numpy as np

from proran.config import SimConfig
from proran.policies import SavedPPOPolicy, no_reservation
from proran.simulator import RANHandoverEnv

from .server import MODEL, ROOT

# Frozen exploratory 32+-UE workloads. These are intentionally independent of
# the six-device educational web traces and the 20-seed primary benchmark.
AUDIT_SCENARIOS = {
    "urban": {"n_ues": 32, "capacity": 60, "speed": 1.0},
    "rush": {"n_ues": 44, "capacity": 60, "speed": 0.9},
    "highway": {"n_ues": 26, "capacity": 52, "speed": 1.65},
    "urllc": {"n_ues": 36, "capacity": 56, "speed": 1.1, "burst_prob": 0.24},
}


def evaluate(seed, preset, policy):
    cfg = SimConfig(
        seed=seed,
        n_ues=preset["n_ues"],
        cell_capacity=preset["capacity"],
        urllc_burst_prob=preset.get("burst_prob", 0.08),
        episode_steps=240,
    )
    env = RANHandoverEnv(cfg)
    observation = env.reset(seed)
    if preset["speed"] != 1.0:
        for ue in env.ues:
            ue.vel *= preset["speed"]
        observation = env.observe()
    for _ in range(240):
        result = env.step(int(policy(*observation)), observation)
        observation = (result.next_state, result.next_mask, result.info["next_context"])
    return env.metrics.summary(cfg.dt_s), env.metrics.handovers


def main() -> None:
    rows = []
    seeds = tuple(range(13_000, 13_008))
    learned = SavedPPOPolicy.load(str(MODEL))
    for scenario, preset in AUDIT_SCENARIOS.items():
        for seed in seeds:
            normal, handovers = evaluate(seed, preset, no_reservation)
            proposed, _ = evaluate(seed, preset, learned)
            rows.append(
                {
                    "scenario": scenario,
                    "seed": seed,
                    "normal_hsr": normal["handover_success_rate"],
                    "ppo_hsr": proposed["handover_success_rate"],
                    "normal_qos": normal["qos_rate"],
                    "ppo_qos": proposed["qos_rate"],
                    "ppo_occupancy": proposed["reservation_occupancy"],
                    "handovers": handovers,
                }
            )
    output = ROOT / "results" / "scenario_audit.csv"
    with output.open("w", newline="", encoding="utf-8") as fh:
        writer = csv.DictWriter(fh, fieldnames=list(rows[0]))
        writer.writeheader()
        writer.writerows(rows)
    macros = ["% Auto-generated by web.scenario_audit; do not hand-edit."]
    aliases = {"urban": "Urban", "rush": "Rush", "highway": "Highway", "urllc": "URLLC"}
    for scenario in AUDIT_SCENARIOS:
        matches = [row for row in rows if row["scenario"] == scenario]
        hsr = np.mean([row["ppo_hsr"] - row["normal_hsr"] for row in matches]) * 100
        qos = np.mean([row["ppo_qos"] - row["normal_qos"] for row in matches]) * 100
        print(f"{scenario:8s}: PPO - baseline HSR {hsr:+.2f} pp, QoS {qos:+.2f} pp")
        macros.append(f"\\newcommand{{\\{aliases[scenario]}HSRGain}}{{{hsr:+.2f}}}")
        macros.append(f"\\newcommand{{\\{aliases[scenario]}QoSGain}}{{{qos:+.2f}}}")
    (ROOT / "results" / "scenario_macros.tex").write_text(
        "\n".join(macros) + "\n", encoding="utf-8"
    )
    print(output)


if __name__ == "__main__":
    main()
