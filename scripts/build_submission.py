"""Sync the paper with the generated results and package the course submission.

    python scripts/build_submission.py sync      # copy figures/tables/macros into paper/
    python scripts/build_submission.py pdf       # sync, then compile paper/main.pdf
    python scripts/build_submission.py package   # sync, then write dist/*.zip
    python scripts/build_submission.py standalone  # one self-contained main.tex for Overleaf
    python scripts/build_submission.py           # sync + package (no compile)

The paper never reads results/ directly, so that paper/ can be uploaded to
Overleaf on its own. ``sync`` is the only way results reach the manuscript, and
tests/test_paper.py fails if paper/ and results/ ever disagree.
"""

from __future__ import annotations

import re
import shutil
import subprocess
import sys
import zipfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
PAPER = ROOT / "paper"
DIST = ROOT / "dist"

# (source, destination inside paper/)
PAPER_ASSETS = [
    *(
        (f"results/care/figures/{name}.pdf", f"figures/{name}.pdf")
        for name in (
            "headline",
            "calibration",
            "tradeoff",
            "frontier",
            "training",
            "policy",
            "sweeps",
        )
    ),
    ("results/care/paper_macros.tex", "generated/paper_macros.tex"),
    ("results/care/main_table.tex", "generated/main_table.tex"),
    ("results/care/frontier_table.tex", "generated/frontier_table.tex"),
]
OVERLEAF_FILES = ["main.tex", "references.bib", "figures", "generated"]

# Everything a grader needs to install, run and regenerate the study.
CODE_ITEMS = [
    "README.md",
    "REPRODUCE.md",
    "requirements.txt",
    "requirements-web.txt",
    "requirements-dev.txt",
    "pyproject.toml",
    "bootstrap.ps1",
    "Dockerfile",
    ".dockerignore",
    "src",
    "web",
    "tests",
    "scripts",
    "results",
    "docs/problem_statement.txt",
    "docs/project_brief.txt",
    "revision_reports",
]
SKIP_PARTS = {"__pycache__", ".pytest_cache", ".ruff_cache"}
SKIP_SUFFIXES = {".pyc", ".aux", ".log", ".out", ".blg", ".synctex.gz"}


def sync() -> None:
    for source, dest in PAPER_ASSETS:
        target = PAPER / dest
        target.parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(ROOT / source, target)
    print(f"synced {len(PAPER_ASSETS)} result files into paper/")


def compile_pdf(directory: Path = PAPER, keep_bbl: bool = False) -> None:
    """pdflatex + bibtex, as Overleaf does. Falls back to Tectonic if present."""
    pdflatex = shutil.which("pdflatex")
    if pdflatex:
        latex = [pdflatex, "-interaction=nonstopmode", "-halt-on-error", "main.tex"]
        steps = [latex, [shutil.which("bibtex") or "bibtex", "main"], latex, latex]
        try:
            for cmd in steps:
                subprocess.run(cmd, cwd=directory, check=True, capture_output=True)
            return
        except subprocess.CalledProcessError:
            print("pdflatex failed (missing packages?); trying Tectonic", file=sys.stderr)
    tectonic = shutil.which("tectonic") or ROOT / ".tools" / "tectonic" / "tectonic.exe"
    if not Path(tectonic).exists():
        raise SystemExit("No working LaTeX found. Install TeX Live/MiKTeX, or use Overleaf.")
    cmd = [str(tectonic), "main.tex"] + (["--keep-intermediates"] if keep_bbl else [])
    subprocess.run(cmd, cwd=directory, check=True, capture_output=True)
    print(f"compiled {directory.relative_to(ROOT).as_posix()}/main.pdf with Tectonic")


def standalone() -> Path:
    """Write dist/Overleaf_SingleFile/: one main.tex with every result, table and
    reference inlined, plus the figures as PNG files in the same folder. Paste
    main.tex into any Overleaf project and upload the PNGs next to it; nothing else
    is needed."""
    build = DIST / "_build"
    shutil.rmtree(build, ignore_errors=True)
    shutil.copytree(PAPER, build, ignore=shutil.ignore_patterns("*.pdf", "*.aux", "*.bbl"))
    for figure in (PAPER / "figures").iterdir():
        shutil.copyfile(figure, build / "figures" / figure.name)
    compile_pdf(build, keep_bbl=True)
    bbl = (build / "main.bbl").read_text(encoding="utf-8")

    tex = (PAPER / "main.tex").read_text(encoding="utf-8")
    macros = (PAPER / "generated" / "paper_macros.tex").read_text(encoding="utf-8")
    used = [
        line
        for line in macros.splitlines()
        if (m := re.match(r"\\newcommand\{\\([A-Za-z]+)\}", line))
        and re.search(r"\\" + m.group(1) + r"(?![A-Za-z])", tex)
    ]
    header = (
        "% Results generated by proran.care_report from the saved per-seed runs.\n"
        "% Do not edit by hand; regenerate with scripts/build_submission.py.\n"
    )
    tex = tex.replace(r"\input{generated/paper_macros.tex}", header + "\n".join(used))
    for name in ("main_table", "frontier_table"):
        body = (PAPER / "generated" / f"{name}.tex").read_text(encoding="utf-8").strip()
        tex = tex.replace(rf"\input{{generated/{name}.tex}}", body)
    tex = tex.replace("\\bibliographystyle{IEEEtran}\n\\bibliography{references}", bbl.strip())
    assert r"\input{" not in tex and r"\bibliography{" not in tex, "standalone still has inputs"

    # Flat layout with PNG images only: upload main.tex and the PNGs side by side.
    tex = tex.replace(r"\graphicspath{{figures/}}", r"\graphicspath{{./}{figures/}}")
    tex = re.sub(r"(\\includegraphics(?:\[[^]]*\])?\{)([^}.]+)\.(?:pdf|jpg)\}", r"\1\2.png}", tex)
    out = DIST / "Overleaf_SingleFile"
    shutil.rmtree(out, ignore_errors=True)
    out.mkdir(parents=True)
    (out / "main.tex").write_text(tex, encoding="utf-8", newline="\n")
    for stem in re.findall(r"\\includegraphics(?:\[[^]]*\])?\{([^}.]+)\.png\}", tex):
        png = ROOT / "results" / "care" / "figures" / f"{stem}.png"
        if png.exists():
            shutil.copyfile(png, out / png.name)
        else:  # The web-lab screenshot is a JPEG; store it losslessly as PNG.
            from PIL import Image

            Image.open(PAPER / "figures" / f"{stem}.jpg").save(out / f"{stem}.png")
    shutil.rmtree(build, ignore_errors=True)

    # Prove it compiles on its own, then drop the build products.
    compile_pdf(out)
    for suffix in (".pdf", ".aux", ".log", ".bbl", ".blg", ".out", ".xdv"):
        (out / f"main{suffix}").unlink(missing_ok=True)
    archive = DIST / "Overleaf_SingleFile.zip"
    with zipfile.ZipFile(archive, "w", zipfile.ZIP_DEFLATED) as zf:
        for file in _files(out):
            zf.write(file, file.relative_to(out).as_posix())
    print(f"wrote {out.relative_to(ROOT)} and {archive.relative_to(ROOT)} ({len(used)} macros)")
    return out


def _files(path: Path):
    if path.is_file():
        yield path
        return
    for item in sorted(path.rglob("*")):
        if item.is_file() and not SKIP_PARTS & set(item.parts):
            if not any(item.name.endswith(s) for s in SKIP_SUFFIXES):
                yield item


def package() -> None:
    DIST.mkdir(exist_ok=True)
    overleaf = DIST / "Overleaf_Source.zip"
    with zipfile.ZipFile(overleaf, "w", zipfile.ZIP_DEFLATED) as zf:
        for name in OVERLEAF_FILES:
            for file in _files(PAPER / name):
                zf.write(file, file.relative_to(PAPER).as_posix())
    print(f"wrote {overleaf.relative_to(ROOT)} ({overleaf.stat().st_size / 1e6:.1f} MB)")
    single = DIST / "Overleaf_SingleFile.zip"

    bundle = DIST / "CARE_Final_Submission.zip"
    prefix = "CARE_Final_Submission"
    with zipfile.ZipFile(bundle, "w", zipfile.ZIP_DEFLATED) as zf:
        zf.write(overleaf, f"{prefix}/Overleaf_Source.zip")
        if single.exists():
            zf.write(single, f"{prefix}/Overleaf_SingleFile.zip")
        pdf = PAPER / "main.pdf"
        if pdf.exists():
            zf.write(pdf, f"{prefix}/CARE_paper.pdf")
        else:
            print("warning: paper/main.pdf not found; run `pdf` first", file=sys.stderr)
        for name in OVERLEAF_FILES:
            for file in _files(PAPER / name):
                zf.write(file, f"{prefix}/paper/{file.relative_to(PAPER).as_posix()}")
        for name in CODE_ITEMS:
            path = ROOT / name
            if not path.exists():
                print(f"warning: {name} missing, skipped", file=sys.stderr)
                continue
            for file in _files(path):
                zf.write(file, f"{prefix}/{file.relative_to(ROOT).as_posix()}")
    size = bundle.stat().st_size / 1e6
    print(f"wrote {bundle.relative_to(ROOT)} ({size:.1f} MB)")
    if size > 100:
        print("warning: bundle exceeds the 100 MB upload limit", file=sys.stderr)


def main(argv: list[str]) -> None:
    steps = argv or ["sync", "package"]
    for step in steps:
        if step == "sync":
            sync()
        elif step == "pdf":
            sync()
            compile_pdf()
        elif step == "package":
            sync()
            package()
        elif step == "standalone":
            sync()
            DIST.mkdir(exist_ok=True)
            standalone()
        else:
            raise SystemExit(f"unknown step {step!r}; use sync, pdf, standalone or package")


if __name__ == "__main__":
    main(sys.argv[1:])
